import { chromium } from 'playwright';
import { once } from 'node:events';
import { makeServer } from '../server.js';
import { BENCHMARK, DEFAULT_MODEL_ID, WEBGPU_LIMITS } from '../local-ai.js';
const FAKE = `self.onmessage = async ({ data }) => { const { id, action } = data; if (action === 'load') { self.postMessage({ id, done: true, result: { loadMs: 0 } }); return; } if (action === 'generate') { await new Promise(r => setTimeout(r, 3000)); self.postMessage({ id, event: 'started' }); self.postMessage({ id, event: 'token', text: '가짜 답변' }); self.postMessage({ id, done: true, result: { text: '가짜 답변', ttftMs: 1, tokens: 3, tokensPerSecond: 1, elapsedMs: 2 } }); return; } self.postMessage({ id, done: true, result: {} }); };`;
const server = makeServer().listen(0, '127.0.0.1');
await once(server, 'listening');
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch();
const page = await browser.newPage();
page.on('pageerror', e => console.log('[pageerror]', e.message.slice(0, 120)));
page.on('dialog', d => d.accept());
await page.route('**/local-ai-worker.bundle.js', route => route.fulfill({ contentType: 'text/javascript', body: FAKE }));
await page.addInitScript(({ settings, limits }) => {
  localStorage.setItem('molu.local-ai.v1', settings);
  Object.defineProperty(navigator, 'gpu', { configurable: true, value: { requestAdapter: async () => ({ info: { vendor: 'x' }, features: new Set(['shader-f16']), limits, requestDevice: async () => null }) } });
}, { settings: JSON.stringify({ catalogVersion: BENCHMARK.version, modelId: DEFAULT_MODEL_ID, momoEnabled: true }), limits: WEBGPU_LIMITS });
const rows = () => page.$$eval('#momo-messages .momo-row', list => list.filter(r => !r.querySelector('.momo-typing')).length);
await page.goto(base);
await page.locator('#home-indicator').click(); await page.locator('[data-app="settings"]').click(); await page.locator('[data-set="ai"]').click();
await page.waitForFunction(() => document.querySelector('.local-ai-settings')?.getAttribute('aria-busy') === 'false');
await page.getByRole('button', { name: '다운로드·로드', exact: true }).click();
await page.waitForFunction(() => /준비 완료/.test(document.querySelector('.local-ai-settings')?.textContent ?? ''), null, { timeout: 30000 });
await page.locator('#home-indicator').click(); await page.locator('[data-app="momo-list"]').click(); await page.locator('[data-mpane="chat"]').click();
await page.locator('#momo-chats .chat-row', { hasText: '아로나' }).click();
await page.waitForFunction(() => document.querySelector('#app-momotalk').hidden === false);
console.log('before', await rows());
await page.locator('#momo-input').fill('중단되어도 남아 있어야 해');
await page.locator('#momo-form .momo-send').click();
await page.waitForFunction(() => document.querySelector('#momo-messages .momo-typing'), null, { timeout: 10000 });
console.log('typing shown, rows', await rows());
await page.reload();
await page.waitForFunction(() => document.querySelector('#app-momotalk').hidden === false, null, { timeout: 30000 });
await page.waitForTimeout(1500);
console.log('after reload rows', await rows(), 'screen', await page.evaluate(() => localStorage.getItem('molu.screen.v1')));
console.log('texts', await page.$$eval('#momo-messages .momo-row', list => list.filter(r => !r.querySelector('.momo-typing')).map(r => r.querySelector('.momo-bubble').textContent.slice(0, 24))));
console.log('replies', await page.evaluate(() => [...document.querySelectorAll('#momo-replies .momo-reply-option')].map(b => b.textContent)));
console.log('input hidden', await page.evaluate(() => document.querySelector('#momo-input').hidden));
await browser.close(); server.close();
